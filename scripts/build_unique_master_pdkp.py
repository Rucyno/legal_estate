import os
import sys
import docx
from docx.shared import Pt, Inches
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.oxml import OxmlElement, parse_xml
from docx.oxml.ns import qn, nsdecls

def generate_pdkp(font_size=10.0, line_spacing=1.04, space_after=1.0, out_path=r"d:\Антигравити\legal_estate\deals\ПДКП_Протасовы_Фирсова.docx"):
    doc = docx.Document()

    # Поля документа «Этажи»
    for s in doc.sections:
        s.top_margin = Inches(0.71)    # 18 mm
        s.bottom_margin = Inches(0.71) # 18 mm
        s.left_margin = Inches(0.79)   # 20 mm
        s.right_margin = Inches(0.59)  # 15 mm
        s.page_width = Inches(8.27)    # 210 mm
        s.page_height = Inches(11.69)  # 297 mm

    BODY_DXA = 9921
    INDENT = Pt(25.0)  # 0.9 см

    def set_p_format(p, f_size=font_size, space_before=0, s_after=space_after, l_spacing=line_spacing, align=WD_ALIGN_PARAGRAPH.JUSTIFY, first_indent=INDENT):
        p.paragraph_format.space_before = Pt(space_before)
        p.paragraph_format.space_after = Pt(s_after)
        p.paragraph_format.line_spacing = l_spacing
        p.paragraph_format.left_indent = Pt(0)
        p.paragraph_format.right_indent = Pt(0)
        p.alignment = align
        if first_indent is not None:
            p.paragraph_format.first_line_indent = first_indent
        else:
            p.paragraph_format.first_line_indent = Pt(0)

    def add_h(doc, text):
        p = doc.add_paragraph()
        set_p_format(p, f_size=font_size, space_before=3.0, s_after=1.5, l_spacing=line_spacing, align=WD_ALIGN_PARAGRAPH.CENTER, first_indent=None)
        p.paragraph_format.keep_with_next = True
        r = p.add_run(text)
        r.bold = True
        r.font.name = "Times New Roman"
        r.font.size = Pt(font_size)
        return p

    def add_p(doc, text="", bold_prefix="", s_after=space_after, space_before=0, align=WD_ALIGN_PARAGRAPH.JUSTIFY, first_indent=INDENT):
        p = doc.add_paragraph()
        set_p_format(p, f_size=font_size, space_before=space_before, s_after=s_after, l_spacing=line_spacing, align=align, first_indent=first_indent)
        if bold_prefix:
            r_pre = p.add_run(bold_prefix)
            r_pre.bold = True
            r_pre.font.name = "Times New Roman"
            r_pre.font.size = Pt(font_size)
        if text:
            r = p.add_run(text)
            r.font.name = "Times New Roman"
            r.font.size = Pt(font_size)
        return p

    def add_header_table(doc, city_text="г. Пенза", date_text="«___» ____________ 2026 года"):
        """Безрамочная таблица 1x2 для города и даты: выравнивание по левому полю листа, 0 стрелок табулятора."""
        tbl = doc.add_table(rows=1, cols=2)
        tbl.alignment = WD_TABLE_ALIGNMENT.LEFT
        tbl.autofit = False

        tblPr = tbl._tbl.tblPr
        tblBorders = parse_xml(r"""
            <w:tblBorders %s >
                <w:top w:val="none"/>
                <w:left w:val="none"/>
                <w:bottom w:val="none"/>
                <w:right w:val="none"/>
                <w:insideH w:val="none"/>
                <w:insideV w:val="none"/>
            </w:tblBorders>
        """ % nsdecls("w"))
        tblPr.append(tblBorders)

        # Левая ячейка 160 pt, правая 336 pt
        widths = [Pt(160), Pt(336)]
        for idx, cell in enumerate(tbl.rows[0].cells):
            cell.width = widths[idx]
            tcPr = cell._tc.get_or_add_tcPr()
            tcBorders = parse_xml(r"""
                <w:tcBorders %s >
                    <w:top w:val="none"/>
                    <w:left w:val="none"/>
                    <w:bottom w:val="none"/>
                    <w:right w:val="none"/>
                </w:tcBorders>
            """ % nsdecls("w"))
            tcPr.append(tcBorders)

            tcMar = parse_xml(r"""
                <w:tcMar %s >
                    <w:top w:w="0" w:type="dxa"/>
                    <w:left w:w="0" w:type="dxa"/>
                    <w:bottom w:w="0" w:type="dxa"/>
                    <w:right w:w="0" w:type="dxa"/>
                </w:tcMar>
            """ % nsdecls("w"))
            tcPr.append(tcMar)

        p_l = tbl.cell(0, 0).paragraphs[0]
        set_p_format(p_l, f_size=font_size, space_before=0, s_after=2.0, l_spacing=line_spacing, align=WD_ALIGN_PARAGRAPH.LEFT, first_indent=None)
        r_l = p_l.add_run(city_text)
        r_l.bold = True
        r_l.font.name = "Times New Roman"
        r_l.font.size = Pt(font_size)

        p_r = tbl.cell(0, 1).paragraphs[0]
        set_p_format(p_r, f_size=font_size, space_before=0, s_after=2.0, l_spacing=line_spacing, align=WD_ALIGN_PARAGRAPH.RIGHT, first_indent=None)
        r_r = p_r.add_run(date_text)
        r_r.bold = True
        r_r.font.name = "Times New Roman"
        r_r.font.size = Pt(font_size)

