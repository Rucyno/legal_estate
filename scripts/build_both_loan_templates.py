    left_lines = [
        "Наименование: ____________________________________",
        "ОГРН: ________________ ИНН/КПП: ___________________",
        "Юр. адрес: ________________________________________",
        "Банк: ____________________________________________",
        "Р/с: _____________________________________________",
        "К/с: __________________ БИК: _____________________"
    ]
    for line in left_lines:
        p = c_left.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
        p.paragraph_format.space_after = Pt(0.5 if compact else 1.0)
        p.paragraph_format.line_spacing = 1.02
        r = p.add_run(line)
        set_run_ru(r, size_pt=7.5 if compact else 8.0)
        
    # Right
