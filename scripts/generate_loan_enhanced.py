def add_sig_line_full(doc, role_title, post_line=True, keep_all=True):
    add_p(doc, role_title, size_pt=9.5, bold=True, indent=0, space_after=1.5, keep_next=True)
    if post_line:
        p_pos = doc.add_paragraph()
        p_pos.paragraph_format.space_after = Pt(1.5)
        p_pos.paragraph_format.keep_with_next = True
        r_pos = p_pos.add_run("Должность: ____________________________________________________________________")
        set_run_ru(r_pos, size_pt=9.0)

    p_line = doc.add_paragraph()
    pPr = p_line._p.get_or_add_pPr()
    pBdr = parse_xml(f"""<w:pBdr {nsdecls("w")}><w:bottom w:val="single" w:sz="6" w:space="1" w:color="000000"/></w:pBdr>""")
    pPr.append(pBdr)
    p_line.paragraph_format.space_after = Pt(1.5)
    p_line.paragraph_format.keep_with_next = True
    r_empty = p_line.add_run(" ")
    set_run_ru(r_empty, size_pt=9.0)
    
    p_sub = doc.add_paragraph()
    pPr_sub = p_sub._p.get_or_add_pPr()
    tabs = parse_xml(f"""<w:tabs {nsdecls("w")}><w:tab w:val="right" w:pos="9640"/></w:tabs>""")
    pPr_sub.append(tabs)
    p_sub.paragraph_format.space_after = Pt(4.0 if keep_all else 1.5)
    if keep_all:
        p_sub.paragraph_format.keep_with_next = True
    r1 = p_sub.add_run("М.П.                     (подпись)                                                 (расшифровка подписи / ФИО)")
    set_run_ru(r1, size_pt=8.0, italic=True)

